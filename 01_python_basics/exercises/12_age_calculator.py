'''20_age_calculator.py

Input current age.

Calculate:

age after 5 years
age after 10 years

Example:

Current age: 20


After 5 years: 25
After 10 years: 30'''

age = int(input("Enter your current age: "))
age_after_5_yrs = age + 5
age_after_10_yrs = age + 10

print(f"After 5 years: {age_after_5_yrs}")
print(f"After 10 yrs: {age_after_10_yrs}")

